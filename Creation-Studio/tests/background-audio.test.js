'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = require('./helpers/app-source')();
test('背景音乐保持同一个播放器，切换音乐、暂停、静音和音量分别生效', () => {
  let audio, plays = 0;
  const state = { config: { ui: {} }, volume: { muted: false } };
  const document = { getElementById: () => audio, body: { appendChild: el => { audio = el; } }, createElement: () => ({ dataset: {}, getAttribute() { return this.src; }, play() { plays++; return Promise.resolve(); }, pause() { this.paused = true; } }) };
  const context = vm.createContext({ state, document, toast() {} });
  vm.runInContext(source.slice(source.indexOf('function syncBackgroundAudio()'), source.indexOf('function currentTheme()')), context);
  context.syncBackgroundAudio();
  assert.equal(audio.src, '/skins/quiet-piano.wav');
  assert.equal(audio.paused, true);
  assert.equal(audio.volume, .3);
  const original = audio;
  Object.assign(state.config.ui, { musicPlaying: true, musicVolume: 65, musicPath: 'C:/音乐/a.mp3' });
  state.volume.muted = true;
  context.syncBackgroundAudio();
  assert.equal(audio, original);
  assert.equal(plays, 1);
  assert.equal(audio.volume, .65);
  assert.equal(audio.muted, true);
  assert.match(audio.src, /^\/api\/file\?path=/);
  state.config.ui.musicPlaying = false;
  context.syncBackgroundAudio();
  assert.equal(audio.paused, true);
});
