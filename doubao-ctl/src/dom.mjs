// Page-side DOM probes. Each export is a JS source string evaluated inside the Doubao renderer.
export const SRC = {
  probe: [
    '(() => {',
    '  const editors = document.querySelectorAll(\'div.ProseMirror[contenteditable="true"]\');',
    '  const ed = editors[0] || null;',
    '  return {',
    '    hasEditor: !!ed,',
    '    editorText: ed ? (ed.innerText || "") : "",',
    '    sendButton: !!document.querySelector(\'[data-testid="chat_input_send_button"]\'),',
    '    breakButton: !!document.querySelector(\'[data-testid="chat_input_local_break_button"]\'),',
    '    busy: !!document.querySelector(\'[data-testid="message_loading"]\'),',
    '    url: location.href,',
    '    botCount: document.querySelectorAll(\'[data-testid="receive_message"]\').length,',
    '    userCount: document.querySelectorAll(\'[data-testid="send_message"]\').length,',
    '  };',
    '})()',
  ].join(String.fromCharCode(10)),

  focusEditor: [
    '(() => {',
    '  const ed = document.querySelector(\'div.ProseMirror[contenteditable="true"]\');',
    '  if (!ed) return { ok: false, reason: "editor-not-found" };',
    '  ed.focus();',
    '  return { ok: true, text: ed.innerText || "" };',
    '})()',
  ].join(String.fromCharCode(10)),

  blurEditor: [
    '(() => { const ed = document.querySelector(\'div.ProseMirror[contenteditable="true"]\'); if (ed) ed.blur(); return true; })()',
  ].join(String.fromCharCode(10)),

  messages: [
    '(() => {',
    '  const containers = [...document.querySelectorAll(\'[data-testid="message-block-container"]\')];',
    '  const items = containers.map((el, i) => {',
    '    const isUser = !!el.querySelector(\'[data-testid="send_message"]\');',
    '    const isBot = !!el.querySelector(\'[data-testid="receive_message"]\');',
    '    const body = el.querySelector(\'[data-testid="message_content"]\') || el;',
    '    const textNodes = [...el.querySelectorAll(\'[data-testid="message_text_content"]\')];',
    '    const text = textNodes.length ? textNodes.map((n) => n.innerText || "").join(String.fromCharCode(10)) : (el.innerText || "");',
    '    return {',
    '      index: i,',
    '      role: isUser ? "user" : (isBot ? "assistant" : "system"),',
    '      id: body ? (body.getAttribute("data-message-id") || null) : null,',
    '      text: text,',
    '    };',
    '  }).filter((m) => m.text && m.text.trim());',
    '  const bots = [...document.querySelectorAll(\'[data-testid="receive_message"]\')];',
    '  const lastBot = bots[bots.length - 1] || null;',
    '  const lastBody = lastBot ? lastBot.querySelector(\'[data-testid="message_content"]\') : null;',
    '  const lastTexts = lastBot ? [...lastBot.querySelectorAll(\'[data-testid="message_text_content"]\')] : [];',
    '  const lastBlock = lastBot ? lastBot.querySelector(\'[data-container-type="block-v2"]\') : null;',
    '  return {',
    '    url: location.href,',
    '    busy: !!document.querySelector(\'[data-testid="message_loading"]\'),',
    '    messages: items,',
    '    lastBotId: lastBody ? lastBody.getAttribute("data-message-id") : null,',
    '    lastBotText: lastBot ? (lastTexts.length ? lastTexts.map((n) => n.innerText || "").join(String.fromCharCode(10)) : (lastBlock ? (lastBlock.innerText || "") : (lastBot.innerText || ""))) : "",',
    '    lastBotFinished: lastBot ? !!lastBot.querySelector(\'[data-testid="message_action_regenerate"]\') : false,',
    '    botCount: bots.length,',
    '  };',
    '})()',
  ].join(String.fromCharCode(10)),

  conversations: [
    '(() => {',
    '  const nodes = [...document.querySelectorAll(\'[data-testid="conversation-list-v2-item"]\')];',
    '  const current = location.href.split("?")[0].replace(/\\/+$/, "").split("/").pop();',
    '  return nodes.map((el, i) => {',
    '    const leaf = [...el.querySelectorAll("span")].find((s) => s.children.length === 0 && (s.textContent || "").trim());',
    '    const id = el.getAttribute("data-conversation-id") || null;',
    '    return {',
    '      index: i,',
    '      id: id,',
    '      title: (leaf ? (leaf.textContent || "") : "").replace(/\\s+/g, " ").trim(),',
    '      active: !!id && id === current,',
    '    };',
    '  }).filter((c) => c.title);',
    '})()',
  ].join(String.fromCharCode(10)),
};

